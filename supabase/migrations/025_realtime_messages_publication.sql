-- Ensure messages table is in the Realtime publication so clients can subscribe to INSERT events.
-- Required for live message notifications on the aspirant dashboard.

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
end $$;
